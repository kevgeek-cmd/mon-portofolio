/**
 * Universal SVG Social Icon Resolver
 */
export const SocialIcon: React.FC<{
  platform?: string;
  icon?: string;
  className?: string;
}> = ({ platform = '', icon = '', className = 'w-4 h-4' }) => {
  const query = (icon + ' ' + platform).toLowerCase().trim();

  if (query.includes('linkedin') || query.includes('work')) return <LinkedinIcon className={className} />;
  if (query.includes('github') || query.includes('code')) return <GithubIcon className={className} />;
  if (query.includes('twitter') || query.includes('x') || query.includes('sports_volleyball')) return <TwitterXIcon className={className} />;
  if (query.includes('instagram') || query.includes('photo_camera')) return <InstagramIcon className={className} />;
  if (query.includes('youtube') || query.includes('smart_display')) return <YoutubeIcon className={className} />;
  if (query.includes('whatsapp') || query.includes('chat')) return <WhatsappIcon className={className} />;
  if (query.includes('tiktok') || query.includes('music_note')) return <TiktokIcon className={className} />;
  if (query.includes('facebook') || query.includes('groups')) return <FacebookIcon className={className} />;
  if (query.includes('dribbble') || query.includes('palette')) return <DribbbleIcon className={className} />;
  if (query.includes('discord') || query.includes('forum')) return <DiscordIcon className={className} />;
  if (query.includes('telegram') || query.includes('send')) return <TelegramIcon className={className} />;
  if (query.includes('mail') || query.includes('email')) return <MailIcon className={className} />;

  return <GlobeIcon className={className} />;
};

